<?php

namespace Fava\Core;

/**
 * Installation config (config/config.php): DB credentials, app key, low level switches.
 * Everything the admin can change from the panel lives in the settings table instead.
 */
class Config
{
    /** @var array|null */
    private static $data = null;

    public static function file(): string
    {
        return CONFIG_DIR . '/config.php';
    }

    public static function load(bool $force = false): array
    {
        if (self::$data === null || $force) {
            $file = self::file();
            $data = [];
            if (is_file($file)) {
                if (function_exists('opcache_invalidate') && $force) {
                    @opcache_invalidate($file, true);
                }
                $data = require $file;
                if (!is_array($data)) {
                    $data = [];
                }
            }
            self::$data = $data;
        }
        return self::$data;
    }

    public static function installed(): bool
    {
        $d = self::load();
        return !empty($d['installed']) && !empty($d['db']);
    }

    /** Dot-notation getter: Config::get('db.driver'). */
    public static function get(string $key, $default = null)
    {
        $value = self::load();
        foreach (explode('.', $key) as $part) {
            if (!is_array($value) || !array_key_exists($part, $value)) {
                return $default;
            }
            $value = $value[$part];
        }
        return $value;
    }

    /** Override values for the current request only (used by the installer and tests). */
    public static function set(string $key, $value): void
    {
        self::load();
        $ref = &self::$data;
        $parts = explode('.', $key);
        foreach ($parts as $i => $part) {
            if ($i === count($parts) - 1) {
                $ref[$part] = $value;
            } else {
                if (!isset($ref[$part]) || !is_array($ref[$part])) {
                    $ref[$part] = [];
                }
                $ref = &$ref[$part];
            }
        }
    }

    /** Persist the config file atomically. */
    public static function write(array $data): void
    {
        $dir = CONFIG_DIR;
        if (!is_dir($dir) && !@mkdir($dir, 0755, true)) {
            throw new \RuntimeException('پوشه config قابل ایجاد نیست: ' . $dir);
        }
        $php = "<?php\n"
            . "// Generated by the installer on " . gmdate('Y-m-d H:i:s') . " UTC.\n"
            . "// Keep this file private. Delete it to run the installer again (the database is left untouched).\n"
            . "if (!defined('APP_ROOT')) { http_response_code(403); exit; }\n\n"
            . 'return ' . var_export($data, true) . ";\n";
        $tmp = $dir . '/config.' . bin2hex(random_bytes(4)) . '.tmp';
        if (@file_put_contents($tmp, $php, LOCK_EX) === false) {
            throw new \RuntimeException('امکان نوشتن در پوشه config وجود ندارد. سطح دسترسی پوشه را بررسی کنید.');
        }
        @chmod($tmp, 0640);
        if (!@rename($tmp, self::file())) {
            @unlink($tmp);
            throw new \RuntimeException('ذخیره فایل پیکربندی انجام نشد.');
        }
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate(self::file(), true);
        }
        self::$data = $data;
    }
}
